// A Postgres database created by the JS backend (branch fp-demo-invest-screens: plain session tokens and OTP codes, no
// schema version) is upgraded in place on the first start: sessions keep working and no secret stays in clear.
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { PGlite } from '@electric-sql/pglite';

describe('migration from the JS backend Postgres schema', () => {
  it('hashes existing session tokens and OTP codes without signing anyone out', async () => {
    const stateDir = fs.mkdtempSync(path.join(os.tmpdir(), 'risips-migpg-'));
    fs.mkdirSync(path.join(stateDir, 'data'));
    const pg = await PGlite.create(path.join(stateDir, 'data', 'pg'));
    // the JS backend's tables as its db.js creates them (the ones this test reads)
    await pg.exec(`
      CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE, mobile TEXT, pin_hash TEXT,
        data JSONB NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ NOT NULL DEFAULT now());
      CREATE TABLE sessions (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token TEXT NOT NULL UNIQUE,
        user_id INTEGER NOT NULL REFERENCES users(id), device TEXT, os TEXT, ip TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(), last_seen TIMESTAMPTZ);
      CREATE TABLE otps (purpose TEXT NOT NULL, target TEXT NOT NULL, code TEXT NOT NULL, expires_at BIGINT NOT NULL,
        attempts INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (purpose, target));
      CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
      INSERT INTO users (email, data) VALUES ('pg@example.com', '{"email_verified":true}');
      INSERT INTO sessions (token, user_id, last_seen) VALUES ('branchTokenAbcdefghijklmnop0123', 1, now());
      INSERT INTO otps (purpose, target, code, expires_at) VALUES ('email', 'pg@example.com', '1234', ${Date.now() + 60e3});
    `);
    await pg.close();

    const { startServer, testDb } = await import('./helpers.ts');
    const t = await startServer({ RISIPS_STATE_DIR: stateDir });
    try {
      const me = await t.call('GET', '/me', undefined, 'branchTokenAbcdefghijklmnop0123');
      assert.equal(me.status, 200, 'the old session still works');
      assert.equal((me.json!.user as Record<string, unknown>).email, 'pg@example.com');
      const db = await testDb();
      const s = (await db.get<Record<string, unknown>>('SELECT * FROM sessions'))!;
      assert.equal(s.token, null, 'the plain token is cleared');
      assert.match(String(s.token_hash), /^[a-f0-9]{64}$/);
      assert.equal(await db.get('SELECT 1 FROM otps WHERE code IS NOT NULL'), null, 'no OTP code left in clear');
      assert.equal((await db.get<{ value: string }>("SELECT value FROM meta WHERE key = 'schema_version'"))!.value, '2');
    } finally {
      await t.close();
    }
  });
});
