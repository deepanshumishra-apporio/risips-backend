// Schema migrations, applied in order at start-up inside one transaction each; the applied version is kept in
// meta.schema_version. Migration 1 is exactly the schema of the JS backend (branch fp-demo-invest-screens), so this
// backend can take over an existing database and the JS one can run on a fresh one.
import type { Queryable } from './connection.ts';
import { log } from '../utils/logger.ts';

interface Db extends Queryable { tx<T>(fn: (tx: Queryable) => Promise<T>): Promise<T>; exec(sql: string): Promise<void> }
type Migration = { version: number; name: string; up: (tx: Queryable) => Promise<void> };

const MIGRATIONS: Migration[] = [
  {
    version: 1,
    name: 'base schema (as the JS backend creates it)',
    up: async (tx) => {
      for (const sql of [
        `CREATE TABLE IF NOT EXISTS users (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email TEXT UNIQUE,
          mobile TEXT,
          pin_hash TEXT,
          data JSONB NOT NULL DEFAULT '{}',
          created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )`,
        `CREATE TABLE IF NOT EXISTS sessions (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          token TEXT NOT NULL UNIQUE,
          user_id INTEGER NOT NULL REFERENCES users(id),
          device TEXT,
          os TEXT,
          ip TEXT,
          created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
          last_seen TIMESTAMPTZ
        )`,
        'CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id)',
        `CREATE TABLE IF NOT EXISTS otps (
          purpose TEXT NOT NULL,
          target TEXT NOT NULL,
          code TEXT NOT NULL,
          expires_at BIGINT NOT NULL,
          attempts INTEGER NOT NULL DEFAULT 0,
          PRIMARY KEY (purpose, target)
        )`,
        `CREATE TABLE IF NOT EXISTS orders (
          id TEXT PRIMARY KEY,
          user_id INTEGER NOT NULL REFERENCES users(id),
          kind TEXT NOT NULL,
          isin TEXT,
          isin_to TEXT,
          amount DOUBLE PRECISION,
          state TEXT,
          data JSONB NOT NULL DEFAULT '{}',
          created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
          updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
          seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
        )`,
        'CREATE INDEX IF NOT EXISTS orders_user ON orders(user_id, created_at)',
        `CREATE TABLE IF NOT EXISTS checkouts (
          id TEXT PRIMARY KEY,
          user_id INTEGER NOT NULL REFERENCES users(id),
          data JSONB NOT NULL DEFAULT '{}',
          created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )`,
        `CREATE TABLE IF NOT EXISTS watchlist (
          user_id INTEGER NOT NULL REFERENCES users(id),
          isin TEXT NOT NULL,
          PRIMARY KEY (user_id, isin)
        )`,
        `CREATE TABLE IF NOT EXISTS ext_imports (
          user_id INTEGER PRIMARY KEY REFERENCES users(id),
          data JSONB NOT NULL DEFAULT '{}',
          updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )`,
        `CREATE TABLE IF NOT EXISTS mfc_sandbox (
          token TEXT PRIMARY KEY,
          data JSONB NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )`,
      ]) await tx.run(sql);
    },
  },
  {
    version: 2,
    name: 'hash session tokens and OTP codes; index for the background jobs',
    up: async (tx) => {
      // Sessions keep only the SHA-256 of each token, so a copy of the database can't be used to sign in. Existing
      // sessions are hashed in place and keep working. The JS backend still runs on this schema (its new sessions
      // write `token`); after a rollback to it, investors simply sign in again.
      await tx.run('ALTER TABLE sessions ADD COLUMN IF NOT EXISTS token_hash TEXT');
      await tx.run("UPDATE sessions SET token_hash = encode(sha256(convert_to(token, 'UTF8')), 'hex') WHERE token IS NOT NULL AND token_hash IS NULL");
      await tx.run('ALTER TABLE sessions ALTER COLUMN token DROP NOT NULL');
      await tx.run('UPDATE sessions SET token = NULL');
      await tx.run('CREATE UNIQUE INDEX IF NOT EXISTS sessions_token_hash ON sessions(token_hash)');
      // OTP codes are stored as HMACs. Open codes live for minutes, so the ones in flight are simply dropped.
      await tx.run('ALTER TABLE otps ADD COLUMN IF NOT EXISTS code_hash TEXT');
      await tx.run('ALTER TABLE otps ALTER COLUMN code DROP NOT NULL');
      await tx.run('DELETE FROM otps');
      await tx.run('CREATE INDEX IF NOT EXISTS orders_kind_state ON orders(kind, state)');
    },
  },
];

export async function migrate(db: Db) {
  await db.exec('CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL)');
  for (const m of MIGRATIONS) {
    const applied = await db.tx(async (tx) => {
      // the row lock makes a second process starting at the same moment wait, then skip what the first applied
      await tx.run("INSERT INTO meta (key, value) VALUES ('schema_version', '0') ON CONFLICT (key) DO NOTHING");
      const row = await tx.get<{ value: string }>("SELECT value FROM meta WHERE key = 'schema_version' FOR UPDATE");
      if (Number(row!.value) >= m.version) return false;
      await m.up(tx);
      await tx.run("UPDATE meta SET value = $1 WHERE key = 'schema_version'", [String(m.version)]);
      return true;
    }).catch((e: Error) => {
      throw new Error(`Database migration ${m.version} (${m.name}) failed: ${e.message}`);
    });
    if (applied) log.info(`Database migration ${m.version} applied: ${m.name}`);
  }
}
